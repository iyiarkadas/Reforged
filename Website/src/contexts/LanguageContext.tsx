type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

const translateText = (text: string) => {
  if (translations[text]) return translations[text];

  const dayMatch = text.match(/^Day (\d+)$/);
  if (dayMatch) return `${dayMatch[1]}. Gün`;

  const traumaMatch = text.match(/^(\d+) parts flagged under care$/);
  if (traumaMatch) return `Takip edilen ${traumaMatch[1]} bölge`;

  return text;
};

const translateElement = (root: ParentNode) => {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();

  while (node) {
    const parent = node.parentElement;
    if (parent && !["SCRIPT", "STYLE"].includes(parent.tagName)) {
      const value = node.textContent ?? "";
      const trimmed = value.trim();
      const translated = translateText(trimmed);
      if (trimmed && translated !== trimmed) {
        node.textContent = value.replace(trimmed, translated);
      }
    }
    node = walker.nextNode();
  }

  root.querySelectorAll?.<HTMLElement>("[placeholder], [title], [aria-label]").forEach((element) => {
    ["placeholder", "title", "aria-label"].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, translateText(value));
    });
  });
};

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language] = useState<Language>(() => localStorage.getItem("reforged-language") === "tr" ? "tr" : "en");

  useEffect(() => {
    document.documentElement.lang = language;
    if (language !== "tr") return;

    translateElement(document.body);
    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE && node.parentNode) translateElement(node.parentNode);
          if (node.nodeType === Node.ELEMENT_NODE) translateElement(node as Element);
        });
      });
    });
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage: (nextLanguage) => {
      if (nextLanguage === language) return;
      localStorage.setItem("reforged-language", nextLanguage);
      window.scrollTo({ top: 0, left: 0 });
      window.location.reload();
    },
    t: language === "tr" ? translateText : (text) => text,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
};
